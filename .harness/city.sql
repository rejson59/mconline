-- Run on a city test database before public opening. Never leaves test claims/blocks.
-- Uses the real anonymous role and security-definer RPCs, not a simulation.
BEGIN;
SET LOCAL ROLE anon;
DO $$
DECLARE a text := encode(sha256(convert_to(clock_timestamp()::text || random()::text,'UTF8')),'hex');
  b text := encode(sha256(convert_to(random()::text || clock_timestamp()::text,'UTF8')),'hex');
  result jsonb; denied boolean; own_hash text;
BEGIN
  ASSERT NOT has_table_privilege('anon','public.blockcraft_blocks','INSERT');
  ASSERT NOT has_table_privilege('anon','public.blockcraft_blocks','UPDATE');
  ASSERT NOT has_table_privilege('anon','public.blockcraft_blocks','DELETE');
  ASSERT NOT has_table_privilege('anon','public.blockcraft_plots','INSERT');
  ASSERT NOT has_table_privilege('anon','public.blockcraft_plots','UPDATE');
  ASSERT NOT has_table_privilege('anon','public.blockcraft_plots','DELETE');
  ASSERT has_function_privilege('anon','public.blockcraft_city_plot(text,text,text,integer,integer,text)','EXECUTE');
  ASSERT has_function_privilege('anon','public.blockcraft_city_write_blocks(text,text,jsonb)','EXECUTE');
  ASSERT NOT EXISTS (SELECT 1 FROM public.blockcraft_plots WHERE world='city' AND (cx,cz) IN ((0,0),(-1,-1),(1,0),(0,1),(1,1)));
  result := public.blockcraft_city_write_blocks('city',a,'[{"x":20,"y":65,"z":20,"id":3,"d":"o"}]');
  ASSERT jsonb_array_length(result->'accepted')=0 AND jsonb_array_length(result->'rejected')=1;
  result := public.blockcraft_city_plot('city',a,'claim',0,0,'Test A'); own_hash := result->>'owner';
  ASSERT own_hash <> a AND length(own_hash)=64;
  result := public.blockcraft_city_write_blocks('city',a,'[{"x":20,"y":65,"z":20,"id":3,"d":"o"}]');
  ASSERT jsonb_array_length(result->'accepted')=1;
  result := public.blockcraft_city_write_blocks('city',b,'[{"x":20,"y":65,"z":20,"id":0,"d":"o"}]');
  ASSERT jsonb_array_length(result->'accepted')=0 AND (result->'rejected'->0->>'id')::int=3;
  result := public.blockcraft_city_write_blocks('city',own_hash,'[{"x":20,"y":65,"z":20,"id":0,"d":"o"}]');
  ASSERT jsonb_array_length(result->'accepted')=0;
  result := public.blockcraft_city_write_blocks('city',a,'[{"x":15,"y":64,"z":20,"id":0,"d":"o"},{"x":20,"y":64,"z":15,"id":0,"d":"o"},{"x":20,"y":0,"z":20,"id":0,"d":"o"},{"x":20,"y":128,"z":20,"id":3,"d":"o"},{"x":20,"y":65,"z":20,"id":3,"d":"n"},{"x":784,"y":65,"z":20,"id":3,"d":"o"}]');
  ASSERT jsonb_array_length(result->'accepted')=0 AND jsonb_array_length(result->'rejected')=6;
  denied := false;
  BEGIN PERFORM public.blockcraft_city_plot('city',b,'claim',0,0,'Test B'); EXCEPTION WHEN raise_exception THEN denied:=true; END;
  ASSERT denied;
  denied := false;
  BEGIN PERFORM public.blockcraft_city_plot('city',b,'release',0,0); EXCEPTION WHEN raise_exception THEN denied:=true; END;
  ASSERT denied;
  PERFORM public.blockcraft_city_plot('city',a,'claim',-1,-1,'Test A');
  result := public.blockcraft_city_write_blocks('city',a,'[{"x":-1,"y":127,"z":-1,"id":10,"d":"o"},{"x":-32,"y":1,"z":-32,"id":3,"d":"o"},{"x":-33,"y":65,"z":-32,"id":3,"d":"o"},{"x":-48,"y":65,"z":-48,"id":3,"d":"o"}]');
  ASSERT jsonb_array_length(result->'accepted')=2 AND jsonb_array_length(result->'rejected')=2;
  PERFORM public.blockcraft_city_plot('city',a,'claim',1,0,'Test A');
  PERFORM public.blockcraft_city_plot('city',a,'claim',0,1,'Test A');
  denied := false;
  BEGIN PERFORM public.blockcraft_city_plot('city',a,'claim',1,1,'Test A'); EXCEPTION WHEN raise_exception THEN denied:=true; END;
  ASSERT denied;
  denied := false;
  BEGIN PERFORM public.blockcraft_city_plot('city',b,'claim',16,0); EXCEPTION WHEN raise_exception THEN denied:=true; END;
  ASSERT denied;
  denied := false;
  BEGIN PERFORM public.blockcraft_city_plot('public',a,'list'); EXCEPTION WHEN raise_exception THEN denied:=true; END;
  ASSERT denied;
  denied := false;
  BEGIN PERFORM public.blockcraft_write_blocks('city',a,'[]'); EXCEPTION WHEN raise_exception THEN denied:=true; END;
  ASSERT denied;
  denied := false;
  BEGIN PERFORM public.blockcraft_city_write_blocks('public',a,'[]'); EXCEPTION WHEN raise_exception THEN denied:=true; END;
  ASSERT denied;
  denied := false;
  BEGIN PERFORM public.blockcraft_city_write_blocks('city',a,'[{"x":20,"y":65,"z":20,"d":"o"}]'); EXCEPTION WHEN raise_exception THEN denied:=true; END;
  ASSERT denied;
  denied := false;
  BEGIN PERFORM public.blockcraft_city_plot('city','bad','list'); EXCEPTION WHEN raise_exception THEN denied:=true; END;
  ASSERT denied;
  PERFORM public.blockcraft_city_plot('city',a,'release',0,0);
  result := public.blockcraft_city_write_blocks('city',a,'[{"x":20,"y":65,"z":20,"id":0,"d":"o"}]');
  ASSERT jsonb_array_length(result->'accepted')=0;
  PERFORM public.blockcraft_city_plot('city',b,'claim',0,0,'Test B');
  result := public.blockcraft_city_write_blocks('city',b,'[{"x":20,"y":65,"z":20,"id":10,"d":"o"}]');
  ASSERT jsonb_array_length(result->'accepted')=1;
  ASSERT (SELECT md5(pg_get_functiondef(oid)) FROM pg_proc WHERE proname='blockcraft_plot')='ec9c1d302e10fb0909f5102447fd6e64';
  ASSERT (SELECT md5(pg_get_functiondef(oid)) FROM pg_proc WHERE proname='blockcraft_write_blocks')='4e2705bb06d5ddbb989f5486c9027c43';
END $$;
ROLLBACK;
SELECT 'City authorization regression passed; all test changes rolled back' AS result;
