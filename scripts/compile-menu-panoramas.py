#!/usr/bin/env python3
"""Optional title backgrounds from pinned Mojang assets; NOT MIT artwork.
PYTHONPATH=.cache/python-tools python3 scripts/compile-menu-panoramas.py
Requires Pillow 11.3.0 and gh. Originals cached outside Git; no runtime requests.
Default 1.20.4 panorama continues using the existing Java GUI asset bundle.
"""
import base64
import hashlib
import io
import json
import subprocess
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
REPO = 'InventivetalentDev/minecraft-assets'
SOURCES = {
    'caves': ('1.18', '65c67a1ffd41640355d0aadb691567a821879b72'),
    'nether': ('1.16', '1bca5976bce1c7c553762aecb04c29f41c7ba96e'),
}

def compile_face(job):
    key, version, commit, face = job
    path = f'assets/minecraft/textures/gui/title/background/panorama_{face}.png'
    cache = ROOT / '.cache/menu-panoramas' / commit / path
    if not cache.exists() or cache.stat().st_size == 0:
        data = json.loads(subprocess.check_output(['gh', 'api', f'repos/{REPO}/contents/{path}?ref={commit}']))
        if data.get('encoding') != 'base64':
            data = json.loads(subprocess.check_output(['gh', 'api', f"repos/{REPO}/git/blobs/{data['sha']}"]))
        cache.parent.mkdir(parents=True, exist_ok=True)
        cache.write_bytes(base64.b64decode(data['content']))
    raw = cache.read_bytes()
    image = Image.open(io.BytesIO(raw)).convert('RGB')
    assert image.size == (1024, 1024)
    # Background is blurred and rendered at capped resolution. Keep the standalone
    # HTML small: optional scenes are explicitly resampled, not exact PNG copies.
    image = image.resize((512, 512), Image.Resampling.LANCZOS)
    out = io.BytesIO()
    image.save(out, format='WEBP', quality=90, method=6)
    encoded = out.getvalue()
    return key, face, 'data:image/webp;base64,' + base64.b64encode(encoded).decode(), {
        'scene': key, 'version': version, 'commit': commit, 'path': path,
        'sourceBytes': len(raw), 'sourceSha256': hashlib.sha256(raw).hexdigest(),
        'outputBytes': len(encoded), 'outputSha256': hashlib.sha256(encoded).hexdigest(),
    }

jobs = [(k, v, c, i) for k, (v, c) in SOURCES.items() for i in range(6)]
results = list(ThreadPoolExecutor(4).map(compile_face, jobs))
art = {key: [''] * 6 for key in SOURCES}
manifest = {'repository': REPO, 'transform': 'Pillow 11.3.0, RGB, 512x512 Lanczos, WebP quality=90 method=6', 'files': []}
for key, face, url, row in results:
    art[key][face] = url
    manifest['files'].append(row)
(ROOT / 'src/game/art/menuPanoramas.generated.ts').write_text(
    '// Generated by scripts/compile-menu-panoramas.py. Resampled Mojang/Microsoft artwork, NOT MIT.\n'
    + 'export const MENU_PANORAMAS: Record<string, readonly string[]> = '
    + json.dumps(art, indent=2) + ';\n')
(ROOT / 'docs/menu-panoramas-manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
print(f'{len(results)} faces, {sum(r[3]["sourceBytes"] for r in results)} original bytes, '
      f'{sum(r[3]["outputBytes"] for r in results)} embedded WebP bytes')
