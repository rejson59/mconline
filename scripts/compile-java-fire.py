#!/usr/bin/env python3
"""Embed pinned Java 1.20.4 flame sheets, unlit campfire texture and ignition sounds.
Original Mojang/Microsoft assets are NOT MIT. No runtime downloads.
"""
import base64, json, subprocess, hashlib, struct
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
REF='90d256dfee7b6fd8014e1bc3b107e64a530c5f9b'
CACHE=ROOT/'.cache/java-fire'
def fetch(path):
    p=CACHE/path
    if not p.exists():
        d=json.loads(subprocess.check_output(['gh','api',f'repos/InventivetalentDev/minecraft-assets/contents/assets/minecraft/{path}?ref={REF}']))
        p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(base64.b64decode(d['content']))
    b=p.read_bytes();print(path,len(b),hashlib.sha256(b).hexdigest());return b
textures={};animations={}
for name in ['fire_0','soul_fire_0','campfire_fire','campfire_log']:
    raw=fetch('textures/block/'+name+'.png');assert raw.startswith(b'\x89PNG')
    textures[name]='data:image/png;base64,'+base64.b64encode(raw).decode()
    if name!='campfire_log':
        meta=json.loads(fetch('textures/block/'+name+'.png.mcmeta'))['animation']
        count=struct.unpack('>II',raw[16:24])[1]//16
        animations[name]={'frames':meta.get('frames',list(range(count))),'frametime':meta.get('frametime',1)}
events=json.loads(fetch('sounds.json'))
keys=['item.flintandsteel.use','block.fire.extinguish']
files={};bank={}
for key in keys:
    variants=events[key]['sounds'];bank[key]=[]
    for raw in variants:
        v={'name':raw} if isinstance(raw,str) else raw
        assert v.get('type','sound')=='sound'
        name=v['name'].removeprefix('minecraft:')
        data=fetch('sounds/'+name+'.ogg');assert data.startswith(b'OggS')
        files[name]=base64.b64encode(data).decode();bank[key].append(v)
header=f'// Generated by scripts/compile-java-fire.py, Java 1.20.4, {REF}.\n// Original Mojang/Microsoft assets, NOT project MIT.\n'
text=header+'export const JAVA_FIRE_TEXTURES: Record<string,string> = '+json.dumps(textures,indent=2)+';\n'
text+='export const JAVA_FIRE_ANIMATIONS: Record<string,{frames:number[];frametime:number}> = '+json.dumps(animations,indent=2)+';\n'
text+='export const FIRE_SOUND_FILES: Record<string,string> = '+json.dumps(files,indent=2)+';\n'
text+='export const FIRE_SOUND_EVENTS: Record<string,{name:string;volume?:number;pitch?:number;weight?:number}[]> = '+json.dumps(bank,indent=2)+';\n'
(ROOT/'src/game/art/javaFire.generated.ts').write_text(text)
