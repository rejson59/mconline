#!/usr/bin/env python3
"""Pinned Java 1.20.4 furnace blockstates/models, loot and exact block sprites; no runtime downloads.
Original Mojang/Microsoft data/art is NOT covered by the project MIT license.
"""
import base64
import hashlib
import json
import struct
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REF = '90d256dfee7b6fd8014e1bc3b107e64a530c5f9b'
REPO = 'InventivetalentDev/minecraft-assets'
OUT = ROOT / '.harness/fixtures/java-facing-1.20.4'
paths = ['assets/minecraft/blockstates/furnace.json']
paths += ['assets/minecraft/models/block/'+n+'.json' for n in ['furnace','furnace_on','orientable','orientable_with_bottom','cube']]
paths += ['data/minecraft/loot_tables/blocks/furnace.json']
paths += ['assets/minecraft/textures/block/'+n+'.png' for n in ['furnace_front','furnace_front_on','furnace_side','furnace_top']]
manifest = {'version': '1.20.4', 'repository': REPO, 'commit': REF, 'files': []}
art = {}
for path in paths:
    cache = ROOT / '.cache/java-facing' / REF / path
    if not cache.exists():
        obj = json.loads(subprocess.check_output(['gh', 'api', f'repos/{REPO}/contents/{path}?ref={REF}']))
        cache.parent.mkdir(parents=True, exist_ok=True)
        cache.write_bytes(base64.b64decode(obj['content']))
    raw = cache.read_bytes()
    if path.endswith('.png'):
        assert raw[:8] == b'\x89PNG\r\n\x1a\n'
        assert struct.unpack('>II', raw[16:24]) == (16, 16)
        art[Path(path).stem] = base64.b64encode(raw).decode()
    else:
        json.loads(raw)
    target = OUT / path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(raw)
    manifest['files'].append({'path': path, 'bytes': len(raw), 'sha256': hashlib.sha256(raw).hexdigest()})
OUT.mkdir(parents=True, exist_ok=True)
(OUT / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
header = f'// Generated by scripts/sync-java-facing.py. Java 1.20.4, {REF}.\n// Original Mojang/Microsoft artwork, NOT project MIT.\n'
(ROOT / 'src/game/art/javaFacing.generated.ts').write_text(header + 'export const JAVA_FACING_TEXTURES: Record<string, string> = ' + json.dumps(art, indent=2) + ';\n')
print(f'Pinned {len(paths)} files, {sum(f["bytes"] for f in manifest["files"])} bytes.')
