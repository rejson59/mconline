#!/usr/bin/env python3
"""Embed six unmodified Java 1.20.4 item PNGs and native brewing audio; requires gh, no Python packages."""
import base64, json, subprocess, hashlib
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
REF = '90d256dfee7b6fd8014e1bc3b107e64a530c5f9b'
CACHE = ROOT / '.cache/java-brewing'
textures = {}
for name in ['blaze_powder','golden_carrot','glistering_melon_slice','glass_bottle','potion','potion_overlay']:
    p = CACHE / f'{name}.png'
    if not p.exists():
        data = json.loads(subprocess.check_output(['gh','api',f'repos/InventivetalentDev/minecraft-assets/contents/assets/minecraft/textures/item/{name}.png?ref={REF}']))
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(base64.b64decode(data['content']))
    raw = p.read_bytes()
    assert raw.startswith(b'\x89PNG')
    textures[name] = base64.b64encode(raw).decode()
    print(name, len(raw), hashlib.sha256(raw).hexdigest())
text = f'// Generated by scripts/compile-java-brewing.py. Java 1.20.4, mirror {REF}.\n// Artwork copyright Mojang/Microsoft and respective authors; NOT MIT.\n'
text += 'export const JAVA_BREWING_ITEMS: Record<string,string> = ' + json.dumps(textures,indent=2) + ';\n'
sounds={}
for name in ['block/brewing_stand/brew1','block/brewing_stand/brew2']:
    p=CACHE / (name+'.ogg')
    if not p.exists():
        data=json.loads(subprocess.check_output(['gh','api',f'repos/InventivetalentDev/minecraft-assets/contents/assets/minecraft/sounds/{name}.ogg?ref={REF}']))
        p.parent.mkdir(parents=True,exist_ok=True)
        p.write_bytes(base64.b64decode(data['content']))
    raw=p.read_bytes();assert raw.startswith(b'OggS')
    sounds[name]=base64.b64encode(raw).decode()
    print(name,len(raw),hashlib.sha256(raw).hexdigest())
text+='export const BREWING_SOUND_FILES: Record<string,string> = '+json.dumps(sounds,indent=2)+';\n'
text+='export const BREWING_SOUND_EVENTS: Record<string,{name:string;volume?:number;pitch?:number;weight?:number}[]> = '+json.dumps({'block.brewing_stand.brew':[{'name':name} for name in sounds]},indent=2)+';\n'
(ROOT / 'src/game/art/javaBrewing.generated.ts').write_text(text)
