#!/usr/bin/env python3
"""Embed original Java 1.20.4 effect samples. No CDN/runtime downloads; artwork is NOT MIT.
Requires Python 3 and authenticated gh. Deterministic pinned mirror, ignored cache.
Music recordings are deliberately not bundled. See public/Minecraft-NOTICE.txt.
"""
import base64, json, subprocess
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor
ROOT=Path(__file__).resolve().parent.parent
REF='90d256dfee7b6fd8014e1bc3b107e64a530c5f9b'
CACHE=ROOT/'.cache/java-sounds'; CACHE.mkdir(parents=True,exist_ok=True)
def fetch(path):
 p=CACHE/path
 if not p.exists():
  data=json.loads(subprocess.check_output(['gh','api',f'repos/InventivetalentDev/minecraft-assets/contents/assets/minecraft/{path}?ref={REF}']))
  p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(base64.b64decode(data['content']))
 return p.read_bytes()
sounds=json.loads(fetch('sounds.json'))
keys=[]
for material in ['stone','wood','grass','sand','glass','wool','slime_block','metal']:
 for action in ['break','place','hit','step']: keys.append(f'block.{material}.{action}')
for mob in ['pig','sheep','cow','chicken','creeper','spider','skeleton','zombie','wolf','villager','iron_golem','enderman','slime','ghast']:
 for action in ['ambient','hurt','death','step']: 
  if f'entity.{mob}.{action}' in sounds: keys.append(f'entity.{mob}.{action}')
keys += [f'block.note_block.{name}' for name in ['harp','basedrum','snare','hat','bass','flute','bell','guitar','iron_xylophone','cow_bell','didgeridoo','bit','banjo','pling']]
keys += ['ui.button.click','block.chest.open','block.chest.close','block.wooden_door.open','block.wooden_door.close',
 'entity.generic.splash','entity.player.hurt','block.bell.use','entity.generic.explode','entity.tnt.primed','entity.item.pickup',
 'entity.generic.eat','entity.generic.drink','entity.arrow.shoot','entity.arrow.hit','entity.player.levelup',
 'block.enchantment_table.use','item.shield.block','ambient.cave','entity.lightning_bolt.thunder','weather.rain',
 'block.portal.ambient','entity.slime.jump']
def resolve(key,seen=()):
 if key in seen: raise ValueError(f'cyclic sound event {key}')
 result=[]
 for raw in sounds[key].get('sounds',[]):
  v={'name':raw} if isinstance(raw,str) else raw.copy()
  if v.get('stream'): continue
  name=v['name'].removeprefix('minecraft:')
  if v.get('type')=='event':
   for child in resolve(name,(*seen,key)):
    result.append({**child,'volume':child.get('volume',1)*v.get('volume',1),'pitch':child.get('pitch',1)*v.get('pitch',1)})
  else: result.append({k:v[k] for k in ['name','volume','pitch','weight'] if k in v} | {'name':name})
 return result
bank={k:resolve(k)[:4] for k in keys}
paths=sorted({v['name'] for variants in bank.values() for v in variants})
def load(name):
 b=fetch('sounds/'+name+'.ogg')
 if not b.startswith(b'OggS'): raise ValueError(f'Not OGG audio: {name}')
 return name,base64.b64encode(b).decode(),len(b)
files=list(ThreadPoolExecutor(6).map(load,paths))
header=f'// Generated by scripts/compile-java-sounds.py. Java 1.20.4; mirror commit {REF}.\n// Original audio copyright Mojang/Microsoft and respective authors; NOT project MIT.\n'
text=header+'export const JAVA_SOUND_FILES: Record<string,string> = '+json.dumps({n:b for n,b,_ in files},indent=2)+';\n'
text+='export const JAVA_SOUND_EVENTS: Record<string,{name:string;volume?:number;pitch?:number;weight?:number}[]> = '+json.dumps(bank,indent=2)+';\n'
(ROOT/'src/game/art/javaSounds.generated.ts').write_text(text)
print(f'{len(bank)} events, {len(files)} original OGG samples, {sum(n for _,_,n in files):,} bytes. Music not bundled.')
