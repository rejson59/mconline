#!/usr/bin/env python3
"""Embed unmodified Java 1.20.4 option widgets/HUD PNGs. Requires gh only."""
import base64
import hashlib
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REF = '90d256dfee7b6fd8014e1bc3b107e64a530c5f9b'
CACHE = ROOT / '.cache/java-options' / REF
FILES = {name: 'widget/' + name for name in (
    'slider', 'slider_highlighted', 'slider_handle', 'slider_handle_highlighted')}
FILES.update({name: 'hud/' + name for name in (
    'crosshair_attack_indicator_background', 'crosshair_attack_indicator_progress',
    'hotbar_attack_indicator_background', 'hotbar_attack_indicator_progress')})
result = {}
for name, path in FILES.items():
    dest = CACHE / (path + '.png')
    if not dest.exists():
        data = json.loads(subprocess.check_output(['gh', 'api',
            f'repos/InventivetalentDev/minecraft-assets/contents/assets/minecraft/textures/gui/sprites/{path}.png?ref={REF}']))
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(base64.b64decode(data['content']))
    raw = dest.read_bytes()
    assert raw.startswith(b'\x89PNG\r\n\x1a\n')
    print(name, len(raw), hashlib.sha256(raw).hexdigest())
    result[name] = base64.b64encode(raw).decode()
text = f'// Generated by scripts/compile-java-options.py, Java 1.20.4 mirror {REF}.\n'
text += '// Artwork copyright Mojang/Microsoft and respective authors; NOT MIT.\n'
text += 'export const JAVA_OPTIONS: Record<string, string> = ' + json.dumps(result, indent=2) + ';\n'
(ROOT / 'src/game/art/javaOptions.generated.ts').write_text(text)
