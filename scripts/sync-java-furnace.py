#!/usr/bin/env python3
"""Pinned Java 1.20.4 furnace reference + exact item sprites; no runtime downloads.
Original Mojang/Microsoft data/art is NOT covered by the project MIT license.
"""
import base64
import hashlib
import json
import struct
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REF = '90d256dfee7b6fd8014e1bc3b107e64a530c5f9b'
REPO = 'InventivetalentDev/minecraft-assets'
OUT = ROOT / '.harness/fixtures/java-furnace-1.20.4'
recipes = ['charcoal', 'iron_ingot_from_smelting_raw_iron', 'gold_ingot_from_smelting_raw_gold', 'glass', 'stone', 'cooked_porkchop', 'iron_ingot_from_smelting_iron_ore', 'gold_ingot_from_smelting_gold_ore']
paths = ['data/minecraft/recipes/' + n + '.json' for n in recipes]
paths += ['data/minecraft/loot_tables/blocks/' + n + '.json' for n in ['iron_ore', 'gold_ore', 'campfire']]
paths += ['assets/minecraft/textures/item/' + n + '.png' for n in ['charcoal', 'raw_iron', 'raw_gold', 'coal', 'iron_ingot', 'gold_ingot']]
manifest = {'version': '1.20.4', 'repository': REPO, 'commit': REF, 'files': []}
art = {}
for path in paths:
    cache = ROOT / '.cache/java-furnace' / REF / path
    if not cache.exists():
        obj = json.loads(subprocess.check_output(['gh', 'api', f'repos/{REPO}/contents/{path}?ref={REF}']))
        cache.parent.mkdir(parents=True, exist_ok=True)
        cache.write_bytes(base64.b64decode(obj['content']))
    raw = cache.read_bytes()
    if path.endswith('.png'):
        assert raw[:8] == b'\x89PNG\r\n\x1a\n'
        assert struct.unpack('>II', raw[16:24]) == (16, 16)
        art[Path(path).stem] = base64.b64encode(raw).decode()
    else:
        json.loads(raw)
    target = OUT / path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(raw)
    manifest['files'].append({'path': path, 'bytes': len(raw), 'sha256': hashlib.sha256(raw).hexdigest()})
OUT.mkdir(parents=True, exist_ok=True)
(OUT / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
header = f'// Generated by scripts/sync-java-furnace.py. Java 1.20.4, {REF}.\n// Original Mojang/Microsoft artwork, NOT project MIT.\n'
(ROOT / 'src/game/art/javaFurnace.generated.ts').write_text(header + 'export const JAVA_FURNACE_ITEMS: Record<string, string> = ' + json.dumps(art, indent=2) + ';\n')
print(f'Pinned {len(paths)} files, {sum(f["bytes"] for f in manifest["files"])} bytes.')
