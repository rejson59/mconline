#!/usr/bin/env python3
"""Pin Java 1.20.4 chest/rail textures; requires gh, no image libraries.
Original artwork is NOT MIT. See public/Minecraft-NOTICE.txt.
"""
import base64,json,subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
REF='90d256dfee7b6fd8014e1bc3b107e64a530c5f9b'
cache=ROOT/'.cache/java-blocks';cache.mkdir(parents=True,exist_ok=True)
def get(path):
 p=cache/path
 if not p.exists():
  obj=json.loads(subprocess.check_output(['gh','api',f'repos/InventivetalentDev/minecraft-assets/contents/assets/minecraft/textures/{path}?ref={REF}']))
  p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(base64.b64decode(obj['content']))
 b=p.read_bytes()
 if not b.startswith(b'\x89PNG\r\n\x1a\n'):raise ValueError(path)
 return 'data:image/png;base64,'+base64.b64encode(b).decode()
chests={key:{'png':get('entity/chest/'+file+'.png'),'w':64,'h':64} for key,file in [('chest','normal'),('chest_left','normal_left'),('chest_right','normal_right')]}
rails={name:get('block/'+name+'.png') for name in ['rail','rail_corner','powered_rail','detector_rail']}
out='// Generated by scripts/compile-java-blocks.py. Java 1.20.4, '+REF+'.\n// Original Mojang/Microsoft artwork, NOT covered by project MIT license.\n'
out+='export const JAVA_CHEST_TEXTURES: Record<string,{png:string;w:number;h:number}> = '+json.dumps(chests,indent=2)+';\n'
out+='export const JAVA_RAIL_TEXTURES: Record<string,string> = '+json.dumps(rails,indent=2)+';\n'
(ROOT/'src/game/art/javaBlocks.generated.ts').write_text(out)
print('Embedded 3 original chest textures and 4 rail textures (Java 1.20.4).')
