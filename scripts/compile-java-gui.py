#!/usr/bin/env python3
"""Compile Java 1.20.4 GUI/bitmap font. Requires gh, Pillow, fonttools, brotli.
Upstream: InventivetalentDev/minecraft-assets, branch 1.20.4; Mojang assets.
Only build-time GitHub API access; no runtime downloads. Cache is not committed.
"""
import base64, io, json, re, subprocess
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parent.parent
CACHE=ROOT/'.cache/java-gui';CACHE.mkdir(parents=True,exist_ok=True)
def fetch(path):
    dest=CACHE/path
    if not dest.exists():
        result=json.loads(subprocess.check_output(['gh','api',f'repos/InventivetalentDev/minecraft-assets/contents/assets/minecraft/{path}?ref=1.20.4']))
        dest.parent.mkdir(parents=True,exist_ok=True);dest.write_bytes(base64.b64decode(result['content']))
    return dest.read_bytes()
src=(ROOT/'scripts/compile-vanilla-art.mjs').read_text()
files=dict(re.findall(r"  (\w+): '(gui/[^']+)'",src))
files.update(inventory_gui='gui/container/inventory.png',crafting_gui='gui/container/crafting_table.png',
 creative_gui='gui/container/creative_inventory/tab_items.png',creative_search_gui='gui/container/creative_inventory/tab_item_search.png',creative_inventory_gui='gui/container/creative_inventory/tab_inventory.png',
 recipe_book='gui/recipe_book.png',recipe_button='gui/sprites/recipe_book/button.png',
 dirt='textures/block/dirt.png',logo='gui/title/minecraft.png',edition='gui/title/edition.png',
 hotbar_offhand='gui/sprites/hud/hotbar_offhand_left.png',hotbar_selection='gui/sprites/hud/hotbar_selection.png')
for name in ['slot_craftable','slot_uncraftable','filter_enabled','filter_disabled','page_forward','page_backward']:
    files[f'recipe_{name}']=f'gui/sprites/recipe_book/{name}.png'
for side in ['top','bottom']:
    for state in ['selected','unselected']:
        files[f'creative_tab_{side}_{state}']=f'gui/sprites/container/creative_inventory/tab_{side}_{state}_1.png'
files['creative_scroller']='gui/sprites/container/creative_inventory/scroller.png'
files['toast_advancement']='gui/sprites/toast/advancement.png'
files['air_empty']='gui/sprites/hud/air_bursting.png'
files.pop('dirt');files={k:'textures/'+v for k,v in files.items()};files['dirt']='textures/gui/options_background.png'
# Six separately embedded faces; the front is also the no-WebGL fallback.
files['panorama']='textures/gui/title/background/panorama_0.png'
for i in range(6): files[f'panorama_{i}']=f'textures/gui/title/background/panorama_{i}.png'
def load(pair):
    name,path=pair
    try:return name,Image.open(io.BytesIO(fetch(path))).convert('RGBA')
    except subprocess.CalledProcessError:
        # No invented texture fallback: absent 1.20.4 names retain existing pack art.
        return name,None
images=dict(ThreadPoolExecutor(5).map(load,files.items()))
missing=[name for name,img in images.items() if img is None]
if missing: raise SystemExit(f'Missing required 1.20.4 GUI sprites: {missing}')
crops={'inventory_gui':(176,166),'crafting_gui':(176,166),'creative_gui':(195,136),'creative_search_gui':(195,136),'creative_inventory_gui':(195,136),
 'villager_gui':(276,166),'anvil_gui':(176,166),'enchanting_gui':(176,166),'brewing_gui':(176,166),'furnace_gui':(176,166)}
output={}
for name,img in images.items():
    if img is None:continue
    if name in crops:img=img.crop((0,0,*crops[name]))
    if name=='chest_gui':
        out=Image.new('RGBA',(176,167));out.paste(img.crop((0,0,176,71)),(0,0));out.paste(img.crop((0,126,176,222)),(0,71));img=out
    data=io.BytesIO();img.save(data,format='PNG',optimize=True);output[name]='data:image/png;base64,'+base64.b64encode(data.getvalue()).decode()
(ROOT/'src/game/art/javaGui.generated.ts').write_text('// Generated by scripts/compile-java-gui.py. Minecraft Java 1.20.4, Mojang/Microsoft.\nexport const JAVA_GUI: Record<string, string> = '+json.dumps(output,ensure_ascii=False,indent=2)+';\n')
# Turn the game's bitmap providers into pixel-aligned font outlines, including Polish.
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
providers=json.loads(fetch('font/include/default.json'))['providers']
glyphs={};metrics={};cmap={}
for provider in providers:
    if provider['type']!='bitmap':continue
    img=Image.open(io.BytesIO(fetch('textures/'+provider['file'].replace('minecraft:','')))).convert('RGBA')
    rows=provider['chars'];cw=img.width//len(rows[0]);ch=img.height//len(rows)
    factor=provider.get('height',8)/ch;ascent=provider['ascent']
    for row,chars in enumerate(rows):
        for col,char in enumerate(chars):
            if char=='\0' or ord(char) in cmap:continue
            pen=TTGlyphPen(None);right=0
            for y in range(ch):
                for x in range(cw):
                    if img.getpixel((col*cw+x,row*ch+y))[3]<128:continue
                    right=max(right,x+1);x0=round(x*factor*64);x1=round((x+1)*factor*64);y0=round((ascent-y*factor)*64);y1=round((ascent-(y+1)*factor)*64)
                    pen.moveTo((x0,y0));pen.lineTo((x0,y1));pen.lineTo((x1,y1));pen.lineTo((x1,y0));pen.closePath()
            name=f'uni{ord(char):04X}';glyphs[name]=pen.glyph();metrics[name]=(round(right*factor+1)*64,0);cmap[ord(char)]=name
pen=TTGlyphPen(None);glyphs['.notdef']=pen.glyph();metrics['.notdef']=(384,0)
glyphs['space']=pen.glyph();metrics['space']=(256,0);cmap[32]='space'
fb=FontBuilder(512,isTTF=True);fb.setupGlyphOrder(['.notdef','space']+[n for n in glyphs if n not in ['.notdef','space']]);fb.setupCharacterMap(cmap);fb.setupGlyf(glyphs);fb.setupHorizontalMetrics(metrics);fb.setupHorizontalHeader(ascent=448,descent=-128);fb.setupOS2(sTypoAscender=448,sTypoDescender=-128,usWinAscent=640,usWinDescent=128);fb.setupNameTable({'copyright':'Glyph artwork Copyright Mojang AB / Microsoft. Not covered by the project MIT license.','familyName':'Java Bitmap','styleName':'Regular','uniqueFontIdentifier':'JavaBitmap1204','fullName':'Java Bitmap 1.20.4','psName':'JavaBitmap'});fb.setupPost();fb.font.flavor='woff2';fb.save(ROOT/'src/assets/java-bitmap.woff2')
print(f'{len(output)} sprites, {len(cmap)} bitmap glyphs compiled')
