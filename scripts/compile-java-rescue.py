#!/usr/bin/env python3
"""Embed absorption hearts, six effect icons/background and the totem sample, Java 1.20.4.
Requires gh. Pinned source; ignored cache; no runtime network or new MIT license.
"""
import base64, json, subprocess
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
REF = '90d256dfee7b6fd8014e1bc3b107e64a530c5f9b'
CACHE = ROOT / '.cache/java-rescue'
def fetch(path):
    target = CACHE / path
    if not target.exists():
        data = json.loads(subprocess.check_output(['gh', 'api', f'repos/InventivetalentDev/minecraft-assets/contents/assets/minecraft/{path}?ref={REF}']))
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(base64.b64decode(data['content']))
    return target.read_bytes()
sprites = {}
for fill in ['full', 'half']:
    raw = fetch(f'textures/gui/sprites/hud/heart/absorbing_{fill}.png')
    assert raw.startswith(b'\x89PNG')
    sprites[f'heart_absorbing_{fill}'] = 'data:image/png;base64,' + base64.b64encode(raw).decode()
for effect, native in {'absorption': 'absorption', 'regen': 'regeneration', 'fire': 'fire_resistance', 'speed': 'speed', 'night': 'night_vision', 'strength': 'strength'}.items():
    raw = fetch(f'textures/mob_effect/{native}.png')
    assert raw.startswith(b'\x89PNG')
    sprites[f'effect_{effect}'] = 'data:image/png;base64,' + base64.b64encode(raw).decode()
raw = fetch('textures/gui/sprites/hud/effect_background.png')
sprites['effect_background'] = 'data:image/png;base64,' + base64.b64encode(raw).decode()
sound = 'item/totem/use_totem'
raw = fetch(f'sounds/{sound}.ogg')
assert raw.startswith(b'OggS')
event = json.loads(fetch('sounds.json'))['item.totem.use']
assert event['sounds'] == [sound]
text = f'// Generated by scripts/compile-java-rescue.py. Java 1.20.4; mirror {REF}.\n// Original artwork/audio copyright Mojang/Microsoft and respective authors; NOT MIT.\n'
text += 'export const RESCUE_SPRITES: Record<string,string> = ' + json.dumps(sprites, indent=2) + ';\n'
text += 'export const RESCUE_SOUND_FILES: Record<string,string> = ' + json.dumps({sound: base64.b64encode(raw).decode()}, indent=2) + ';\n'
text += 'export const RESCUE_SOUND_EVENTS: Record<string,{name:string;volume?:number;pitch?:number;weight?:number}[]> = ' + json.dumps({'item.totem.use': [{'name': sound}]}, indent=2) + ';\n'
(ROOT / 'src/game/art/javaRescue.generated.ts').write_text(text)
print(f'{len(sprites)} original sprites, 1 totem event; {len(raw)} OGG bytes')
